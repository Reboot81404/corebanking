CREATE TABLE IF NOT EXISTS payment_idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation VARCHAR(40) NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    response_status INTEGER NOT NULL,
    response_payload TEXT NOT NULL,
    transaction_history_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_payment_idempotency UNIQUE (operation, idempotency_key),
    CONSTRAINT uk_payment_idempotency_history UNIQUE (transaction_history_id),
    CONSTRAINT fk_payment_idempotency_history FOREIGN KEY (transaction_history_id) REFERENCES transaction_histories(id)
);

CREATE INDEX IF NOT EXISTS idx_payment_idempotency_lookup ON payment_idempotency_records(operation, idempotency_key);
