-- Authentication identities are intentionally separate from customer profile data.
-- Existing customer rows remain untouched; an identity is created only through explicit provisioning.
CREATE TABLE user_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    customer_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_identities_username UNIQUE (username),
    CONSTRAINT uk_user_identities_customer UNIQUE (customer_id),
    CONSTRAINT fk_user_identities_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
    CONSTRAINT chk_user_identities_username_normalized CHECK (username = LOWER(TRIM(username))),
    CONSTRAINT chk_user_identities_role CHECK (role IN ('CUSTOMER', 'BANK_OPERATOR', 'AUDITOR', 'ADMIN')),
    CONSTRAINT chk_user_identities_status CHECK (status IN ('ACTIVE', 'LOCKED', 'DISABLED')),
    CONSTRAINT chk_user_identities_customer_link CHECK (
        (role = 'CUSTOMER' AND customer_id IS NOT NULL)
        OR (role IN ('BANK_OPERATOR', 'AUDITOR', 'ADMIN') AND customer_id IS NULL)
    )
);
