CREATE SEQUENCE IF NOT EXISTS account_number_seq
    START WITH 100000000000000
    INCREMENT BY 1
    MINVALUE 100000000000000
    MAXVALUE 9999999999999999;

CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tckn VARCHAR(11) NOT NULL,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone_number VARCHAR(13) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_customers_tckn UNIQUE (tckn),
    CONSTRAINT uk_customers_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iban VARCHAR(26) NOT NULL,
    balance NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(10) NOT NULL,
    customer_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_accounts_iban UNIQUE (iban),
    CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);

CREATE TABLE IF NOT EXISTS transaction_histories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_iban VARCHAR(255) NOT NULL,
    receiver_iban VARCHAR(255) NOT NULL,
    amount NUMERIC(38, 2) NOT NULL,
    currency VARCHAR(255) NOT NULL,
    timestamp TIMESTAMP NOT NULL
);
