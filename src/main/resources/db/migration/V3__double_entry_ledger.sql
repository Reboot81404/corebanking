-- Flyway Migration V3: Double-entry Ledger Schema and Cutover
-- Creates ledger_accounts, journal_entries, and journal_entry_lines tables.
-- Seeds initial opening balance clearing accounts and customer deposit accounts with opening cutover entries.

CREATE TABLE IF NOT EXISTS ledger_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_code VARCHAR(64) NOT NULL,
    name VARCHAR(100) NOT NULL,
    account_type VARCHAR(40) NOT NULL,
    normal_balance VARCHAR(20) NOT NULL,
    currency VARCHAR(10) NOT NULL,
    bank_account_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_ledger_accounts_code UNIQUE (account_code),
    CONSTRAINT uk_ledger_accounts_bank_account UNIQUE (bank_account_id),
    CONSTRAINT fk_ledger_accounts_bank_account FOREIGN KEY (bank_account_id) REFERENCES accounts(id)
);

CREATE TABLE IF NOT EXISTS journal_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_number VARCHAR(64) NOT NULL,
    transaction_history_id BIGINT,
    transaction_type VARCHAR(40) NOT NULL,
    currency VARCHAR(10) NOT NULL,
    description VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    posted_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_journal_entries_reference UNIQUE (reference_number),
    CONSTRAINT uk_journal_entries_history UNIQUE (transaction_history_id),
    CONSTRAINT fk_journal_entries_history FOREIGN KEY (transaction_history_id) REFERENCES transaction_histories(id)
);

CREATE TABLE IF NOT EXISTS journal_entry_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_entry_id BIGINT NOT NULL,
    ledger_account_id BIGINT NOT NULL,
    debit_amount NUMERIC(19, 2) NOT NULL DEFAULT 0.00,
    credit_amount NUMERIC(19, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT fk_jel_entry FOREIGN KEY (journal_entry_id) REFERENCES journal_entries(id),
    CONSTRAINT fk_jel_account FOREIGN KEY (ledger_account_id) REFERENCES ledger_accounts(id),
    CONSTRAINT chk_jel_amounts CHECK (
        debit_amount >= 0.00 AND credit_amount >= 0.00
        AND ((debit_amount > 0.00 AND credit_amount = 0.00) OR (debit_amount = 0.00 AND credit_amount > 0.00))
    )
);

CREATE INDEX IF NOT EXISTS idx_journal_entries_history ON journal_entries(transaction_history_id);
CREATE INDEX IF NOT EXISTS idx_jel_entry ON journal_entry_lines(journal_entry_id);
CREATE INDEX IF NOT EXISTS idx_jel_account ON journal_entry_lines(ledger_account_id);

