-- Cutover: For existing accounts with balance > 0, generate opening balance journal entry and lines
-- 1. Create opening journal entries
INSERT INTO journal_entries (reference_number, transaction_history_id, transaction_type, currency, description, status, created_at, posted_at)
SELECT
    CONCAT('OPENING-BAL-', a.id),
    NULL,
    'OPENING_BALANCE',
    a.currency,
    CONCAT('Opening balance cutover for account ', a.iban),
    'POSTED',
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP
FROM accounts a
WHERE a.balance > 0.00
  AND NOT EXISTS (
      SELECT 1 FROM journal_entries je WHERE je.reference_number = CONCAT('OPENING-BAL-', a.id)
  );

-- 2. Create debit line on corresponding CLEARING account
INSERT INTO journal_entry_lines (journal_entry_id, ledger_account_id, debit_amount, credit_amount)
SELECT
    je.id,
    clearing_la.id,
    a.balance,
    0.00
FROM accounts a
JOIN journal_entries je ON je.reference_number = CONCAT('OPENING-BAL-', a.id)
JOIN ledger_accounts clearing_la ON clearing_la.account_code = CONCAT('CLEARING-', a.currency)
WHERE a.balance > 0.00
  AND NOT EXISTS (
      SELECT 1 FROM journal_entry_lines jel WHERE jel.journal_entry_id = je.id AND jel.ledger_account_id = clearing_la.id
  );

-- 3. Create credit line on customer deposit account
INSERT INTO journal_entry_lines (journal_entry_id, ledger_account_id, debit_amount, credit_amount)
SELECT
    je.id,
    deposit_la.id,
    0.00,
    a.balance
FROM accounts a
JOIN journal_entries je ON je.reference_number = CONCAT('OPENING-BAL-', a.id)
JOIN ledger_accounts deposit_la ON deposit_la.bank_account_id = a.id
WHERE a.balance > 0.00
  AND NOT EXISTS (
      SELECT 1 FROM journal_entry_lines jel WHERE jel.journal_entry_id = je.id AND jel.ledger_account_id = deposit_la.id
  );
